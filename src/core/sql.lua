local U = require("core.util")

local M = {}

M.CONNECT = [[
select current_user, current_database(), coalesce(host(inet_server_addr()), 'local socket'),
  coalesce(inet_server_port()::text, ''), current_setting('server_version');
select nspname from pg_namespace
where nspname !~ '^pg_' and nspname <> 'information_schema'
order by nspname;
]]

function M.relations(schema)
  return [[
select c.relname, c.relkind, c.reltuples::bigint
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname = ]] .. U.literal(schema) .. [[ and c.relkind in ('r', 'p', 'v', 'm', 'f')
order by c.relname;
]]
end

local function regclass(schema, name)
  return U.literal(U.qualified(schema, name)) .. "::regclass"
end

-- psql's \gset keeps the primary key order in a variable, so the page query
-- pages in a stable order without a second round trip.
function M.page(schema, name, limit, offset)
  local target = U.qualified(schema, name)
  local order = [[
select coalesce('order by ' || string_agg(quote_ident(a.attname), ', ' order by k.n), '') as order_clause
from pg_index i
cross join lateral unnest(i.indkey) with ordinality as k(attnum, n)
join pg_attribute a on a.attrelid = i.indrelid and a.attnum = k.attnum
where i.indrelid = ]] .. regclass(schema, name) .. " and i.indisprimary \\gset\n"
  local count = string.format("select count(*) from %s;\n", target)
  local rows = string.format("select * from %s :order_clause limit %d offset %d;\n", target, limit, offset)
  return order .. count .. rows
end

function M.structure(schema, name)
  local rel = regclass(schema, name)
  return [[
select c.relkind, pg_size_pretty(pg_total_relation_size(c.oid)), c.reltuples::bigint,
  coalesce(obj_description(c.oid, 'pg_class'), ''),
  case when c.relkind in ('v', 'm') then pg_get_viewdef(c.oid, true) else '' end
from pg_class c where c.oid = ]] .. rel .. [[;
select a.attname, format_type(a.atttypid, a.atttypmod),
  case when a.attnotnull then 'not null' else 'null' end,
  case
    when a.attidentity = 'a' then 'generated always as identity'
    when a.attidentity = 'd' then 'generated by default as identity'
    when a.attgenerated = 's' then 'generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
    else coalesce(pg_get_expr(d.adbin, d.adrelid), '')
  end,
  concat_ws(', ',
    case when exists (select 1 from pg_constraint p where p.conrelid = a.attrelid and p.contype = 'p'
      and a.attnum = any(p.conkey)) then 'PK' end,
    case when exists (select 1 from pg_constraint f where f.conrelid = a.attrelid and f.contype = 'f'
      and a.attnum = any(f.conkey)) then 'FK' end),
  coalesce(col_description(a.attrelid, a.attnum), '')
from pg_attribute a
left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
where a.attrelid = ]] .. rel .. [[ and a.attnum > 0 and not a.attisdropped
order by a.attnum;
select c.conname, c.contype, pg_get_constraintdef(c.oid, true)
from pg_constraint c where c.conrelid = ]] .. rel .. [[ order by
  case c.contype when 'p' then 0 when 'f' then 1 when 'u' then 2 else 3 end, c.conname;
select ic.relname, pg_get_indexdef(i.indexrelid),
  case when i.indisprimary then 'primary' when i.indisunique then 'unique' else '' end,
  pg_size_pretty(pg_relation_size(i.indexrelid))
from pg_index i join pg_class ic on ic.oid = i.indexrelid
where i.indrelid = ]] .. rel .. [[ order by i.indisprimary desc, ic.relname;
select c.conrelid::regclass::text, c.conname, pg_get_constraintdef(c.oid, true)
from pg_constraint c where c.confrelid = ]] .. rel .. [[ and c.contype = 'f'
order by 1, 2;
]]
end

function M.query(text)
  return "\\timing on\n\\set QUIET off\n\\set FETCH_COUNT 1000\n" .. text .. "\n"
end

return M
